#!/usr/bin/env python3
"""Resolve public Docker Hub images to immutable multi-platform index digests."""
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parent.parent
IMAGES = {
    'CHATWOOT_CE_IMAGE': ('chatwoot/chatwoot', 'v4.20.1-ce'),
    'POSTGRES_IMAGE': ('pgvector/pgvector', 'pg16'),
    'REDIS_IMAGE': ('library/redis', '7.2-alpine'),
    'NGINX_IMAGE': ('library/nginx', 'stable-alpine'),
    'NODE_IMAGE': ('library/node', '24.22.1-alpine'),
    'PYTHON_IMAGE': ('library/python', '3.12-slim'),
    'CLAMAV_IMAGE': ('clamav/clamav', 'stable'),
}
ACCEPT = ', '.join([
    'application/vnd.oci.image.index.v1+json',
    'application/vnd.docker.distribution.manifest.list.v2+json',
])


def fetch(url, headers=None):
    with urlopen(Request(url, headers=headers or {}), timeout=60) as response:
        return response.read(), response.headers


def main():
    records = {}
    for variable, (repository, tag) in IMAGES.items():
        query = urlencode({'service': 'registry.docker.io', 'scope': f'repository:{repository}:pull'})
        token = json.loads(fetch(f'https://auth.docker.io/token?{query}')[0])['token']
        body, headers = fetch(
            f'https://registry-1.docker.io/v2/{repository}/manifests/{tag}',
            {'Authorization': f'Bearer {token}', 'Accept': ACCEPT},
        )
        digest = 'sha256:' + hashlib.sha256(body).hexdigest()
        if headers.get('Docker-Content-Digest') != digest:
            raise RuntimeError(f'Digest mismatch: {repository}:{tag}')
        manifest = json.loads(body)
        platforms = [item['platform'] for item in manifest.get('manifests', [])]
        for architecture in (('amd64',) if variable == 'CLAMAV_IMAGE' else ('arm64', 'amd64')):
            if not any(p.get('os') == 'linux' and p.get('architecture') == architecture for p in platforms):
                raise RuntimeError(f'Missing linux/{architecture}: {repository}:{tag}')
        reference = f'{repository}:{tag}@{digest}'
        records[variable] = {'reference': reference, 'digest': digest, 'platforms': platforms}
        print(f'{variable}={reference}')
    evidence = {'resolved_at': datetime.now(timezone.utc).isoformat(), 'images': records}
    (ROOT / 'infra/images.lock.json').write_text(json.dumps(evidence, indent=2) + '\n')
    (ROOT / 'infra/images.lock.env').write_text(
        '# Generated by scripts/lock-images.py; review changes before upgrading.\n'
        + ''.join(f'{key}={value["reference"]}\n' for key, value in records.items())
    )


if __name__ == '__main__':
    main()
